#!/usr/bin/env python3
"""Generate docs/PROGRESS.md and resources/progress.svg from the TH02 ledgers.

The only input is config/rec98_th02_units.csv (written by build_th02.py
--write-ledger). CODE bytes are split into:

* source  - C/C++ contributions (ReC98 or src/) byte-equal to the target
* differs - C/C++ contributions with differing bytes
* asm     - ReC98 assembly in game segments: the open frontier
* library - Borland runtime, c0 and the asm files' _TEXT (master.lib etc.)
"""

from __future__ import annotations

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LEDGER = ROOT / "config" / "rec98_th02_units.csv"
PRODUCTS = ("OP.EXE", "MAIN.EXE", "MAINE.EXE")
COLORS = {"source": "#55c7a6", "differs": "#f7768e", "asm": "#e0af68", "library": "#565f89"}
LABELS = {
    "source": "C/C++ byte-equal",
    "differs": "C/C++ differing",
    "asm": "ASM game code (open)",
    "library": "runtime + asm _TEXT (mostly master.lib)",
}


def bucket(row: dict[str, str]) -> str | None:
    if row["class"] != "CODE":
        return None
    kind = row["kind"]
    if kind == "rec98-c":
        return "source" if row["state"] == "byte-equal" else "differs"
    if kind == "rec98-asm":
        return "asm"
    return "library"


def totals() -> tuple[dict[str, dict[str, int]], bool]:
    result = {product: dict.fromkeys(COLORS, 0) for product in PRODUCTS}
    zun = False
    with LEDGER.open(encoding="utf-8") as stream:
        for row in csv.DictReader(stream):
            if row["product"] == "ZUN.COM":
                zun = row["state"] == "byte-equal"
                continue
            key = bucket(row)
            if key:
                result[row["product"]][key] += int(row["length"])
    return result, zun


def svg(data: dict[str, dict[str, int]], zun: bool) -> str:
    width, left, bar = 760, 150, 560
    rows = []
    y = 96
    for product in PRODUCTS:
        values = data[product]
        game = values["source"] + values["differs"] + values["asm"]
        share = 100 * values["source"] / game if game else 0
        rows.append(f'<text x="24" y="{y + 13}" fill="#f4f4f5" font-family="sans-serif" font-size="16" font-weight="600">{product}</text>')
        rows.append(f'<rect x="{left}" y="{y}" width="{bar}" height="16" rx="4" fill="#353b52"/>')
        x = float(left)
        total = sum(values.values())
        for key in ("source", "differs", "asm", "library"):
            w = bar * values[key] / total if total else 0
            if w:
                rows.append(f'<rect x="{x:.2f}" y="{y}" width="{w:.2f}" height="16" fill="{COLORS[key]}"/>')
            x += w
        rows.append(
            f'<text x="{left}" y="{y + 36}" fill="#c8cad2" font-family="sans-serif" font-size="12">'
            f'Game segments in C/C++, byte-equal: {values["source"]:,} / {game:,} B ({share:.1f}%) · '
            f'ASM {values["asm"]:,} B · library {values["library"]:,} B</text>'
        )
        y += 64
    rows.append(f'<text x="24" y="{y + 13}" fill="#f4f4f5" font-family="sans-serif" font-size="16" font-weight="600">ZUN.COM</text>')
    rows.append(f'<text x="{left}" y="{y + 13}" fill="#c8cad2" font-family="sans-serif" font-size="12">'
                f'{"Whole file byte-equal (ZUNINIT, ZUN_RES via ReC98 zungen)" if zun else "differs"}</text>')
    y += 40
    legend = []
    x = 24
    for key in ("source", "differs", "asm", "library"):
        legend.append(f'<rect x="{x}" y="{y}" width="12" height="12" rx="2" fill="{COLORS[key]}"/>')
        legend.append(f'<text x="{x + 18}" y="{y + 11}" fill="#c8cad2" font-family="sans-serif" font-size="12">{LABELS[key]}</text>')
        x += 180
    height = y + 36
    return "\n".join([
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img" aria-label="TH02 reconstruction progress">',
        "  <title>TH02 reconstruction progress by artifact</title>",
        "  <desc>CODE bytes per linker-map contribution, compared with the original Japanese executables. Generated by scripts/progress.py.</desc>",
        f'  <rect x="0.5" y="0.5" width="{width - 1}" height="{height - 1}" rx="16" fill="#1f2335" stroke="#353b52"/>',
        '  <text x="24" y="39" fill="#f4f4f5" font-family="sans-serif" font-size="22" font-weight="600">TH02 reconstruction progress</text>',
        '  <text x="24" y="64" fill="#c8cad2" font-family="sans-serif" font-size="13">CODE bytes by linker-map contribution · pinned ReC98 + local patches vs. original binaries</text>',
        *("  " + line for line in rows + legend),
        "</svg>",
        "",
    ])


def markdown(data: dict[str, dict[str, int]], zun: bool) -> str:
    lines = [
        "# Progress",
        "",
        "Generated by `scripts/progress.py` from `config/rec98_th02_units.csv`.",
        "Bytes are CODE-class linker-map contributions compared with the original",
        "Japanese executables. Library covers the Borland runtime, c0 and the",
        "assembly files' `_TEXT`. That `_TEXT` is mostly master.lib, but it also",
        "holds some ZUN assembly (`th02/formats/pfopen.asm` in OP/MAINE, `mpn_put_8`",
        "and a few others in MAIN) that is not yet split out, so the last column is",
        "the C/C++ share of the game *segments*, not of every ZUN-written byte.",
        "",
        "| Product | C/C++ byte-equal | C/C++ differing | ASM game code | Library | Game segments in C/C++ |",
        "| --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for product in PRODUCTS:
        v = data[product]
        game = v["source"] + v["differs"] + v["asm"]
        share = 100 * v["source"] / game if game else 0
        lines.append(f"| {product} | {v['source']:,} | {v['differs']:,} | {v['asm']:,} | {v['library']:,} | {share:.1f}% |")
    lines += ["", f"ZUN.COM: whole file {'byte-equal' if zun else 'differs'}.", ""]
    return "\n".join(lines)


def main() -> int:
    data, zun = totals()
    (ROOT / "resources").mkdir(exist_ok=True)
    (ROOT / "resources" / "progress.svg").write_text(svg(data, zun), encoding="utf-8")
    (ROOT / "docs" / "PROGRESS.md").write_text(markdown(data, zun), encoding="utf-8")
    print((ROOT / "docs" / "PROGRESS.md").read_text(encoding="utf-8"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
